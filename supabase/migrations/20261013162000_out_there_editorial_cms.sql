-- Admin-only editorial publishing for the Out There Field Notes section.

alter table public.out_there_posts
  add column if not exists field_note_number bigint generated by default as identity,
  add column if not exists map_note text;

alter table public.out_there_posts
  drop constraint if exists out_there_posts_title_length_check,
  drop constraint if exists out_there_posts_dek_length_check,
  drop constraint if exists out_there_posts_body_length_check,
  drop constraint if exists out_there_posts_city_length_check,
  drop constraint if exists out_there_posts_map_label_length_check,
  drop constraint if exists out_there_posts_map_note_length_check,
  drop constraint if exists out_there_posts_field_note_number_check;

alter table public.out_there_posts
  add constraint out_there_posts_title_length_check
    check (char_length(title) between 3 and 160),
  add constraint out_there_posts_dek_length_check
    check (dek is null or char_length(dek) between 1 and 360),
  add constraint out_there_posts_body_length_check
    check (body is null or char_length(body) between 1 and 12000),
  add constraint out_there_posts_city_length_check
    check (city is null or char_length(city) between 2 and 120),
  add constraint out_there_posts_map_label_length_check
    check (map_label is null or char_length(map_label) between 2 and 160),
  add constraint out_there_posts_map_note_length_check
    check (map_note is null or char_length(map_note) between 2 and 360),
  add constraint out_there_posts_field_note_number_check
    check (field_note_number is null or field_note_number > 0);

create unique index if not exists out_there_field_note_number_idx
  on public.out_there_posts (field_note_number)
  where field_note_number is not null;

create table if not exists public.out_there_media (
  id uuid primary key default gen_random_uuid(),
  post_id uuid not null references public.out_there_posts(id) on delete cascade,
  storage_path text not null check (char_length(storage_path) between 3 and 1000),
  alt_text text not null check (char_length(alt_text) between 1 and 300),
  caption text check (caption is null or char_length(caption) between 1 and 500),
  sort_order smallint not null default 0 check (sort_order between 0 and 49),
  created_at timestamptz not null default now(),
  unique (post_id, storage_path)
);

create index if not exists out_there_media_post_sort_idx
  on public.out_there_media (post_id, sort_order, created_at);

alter table public.out_there_media enable row level security;

revoke all on table public.out_there_posts from anon, authenticated;
grant select on table public.out_there_posts to anon, authenticated;
grant insert, update, delete on table public.out_there_posts to authenticated;

revoke all on table public.out_there_media from anon, authenticated;
grant select on table public.out_there_media to anon, authenticated;
grant insert, update, delete on table public.out_there_media to authenticated;

grant usage, select on sequence public.out_there_posts_field_note_number_seq to authenticated;

drop policy if exists published_out_there_posts_are_public on public.out_there_posts;
drop policy if exists published_or_admin_out_there_posts_are_visible on public.out_there_posts;
create policy published_or_admin_out_there_posts_are_visible
on public.out_there_posts for select
to anon, authenticated
using (status = 'published' or private.is_admin());

drop policy if exists admins_insert_out_there_posts on public.out_there_posts;
create policy admins_insert_out_there_posts
on public.out_there_posts for insert
to authenticated
with check (
  private.is_admin()
  and author_id = (select auth.uid())
);

drop policy if exists admins_update_out_there_posts on public.out_there_posts;
create policy admins_update_out_there_posts
on public.out_there_posts for update
to authenticated
using (private.is_admin())
with check (private.is_admin());

drop policy if exists admins_delete_out_there_posts on public.out_there_posts;
create policy admins_delete_out_there_posts
on public.out_there_posts for delete
to authenticated
using (private.is_admin());

drop policy if exists published_or_admin_out_there_media_are_visible on public.out_there_media;
create policy published_or_admin_out_there_media_are_visible
on public.out_there_media for select
to anon, authenticated
using (
  private.is_admin()
  or exists (
    select 1
    from public.out_there_posts post
    where post.id = post_id
      and post.status = 'published'
  )
);

drop policy if exists admins_insert_out_there_media on public.out_there_media;
create policy admins_insert_out_there_media
on public.out_there_media for insert
to authenticated
with check (private.is_admin());

drop policy if exists admins_update_out_there_media on public.out_there_media;
create policy admins_update_out_there_media
on public.out_there_media for update
to authenticated
using (private.is_admin())
with check (private.is_admin());

drop policy if exists admins_delete_out_there_media on public.out_there_media;
create policy admins_delete_out_there_media
on public.out_there_media for delete
to authenticated
using (private.is_admin());

drop policy if exists admins_read_editorial_media_objects on storage.objects;
create policy admins_read_editorial_media_objects
on storage.objects for select
to authenticated
using (
  bucket_id = 'editorial-media'
  and private.is_admin()
);

drop policy if exists admins_upload_editorial_media_objects on storage.objects;
create policy admins_upload_editorial_media_objects
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'editorial-media'
  and private.is_admin()
  and (storage.foldername(name))[1] = (select auth.uid())::text
  and (storage.foldername(name))[2] = 'out-there'
);

drop policy if exists admins_update_editorial_media_objects on storage.objects;
create policy admins_update_editorial_media_objects
on storage.objects for update
to authenticated
using (
  bucket_id = 'editorial-media'
  and private.is_admin()
)
with check (
  bucket_id = 'editorial-media'
  and private.is_admin()
);

drop policy if exists admins_delete_editorial_media_objects on storage.objects;
create policy admins_delete_editorial_media_objects
on storage.objects for delete
to authenticated
using (
  bucket_id = 'editorial-media'
  and private.is_admin()
);
